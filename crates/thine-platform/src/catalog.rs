#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_all_done() {
        assert!(FEATURES.len() >= 50);
        let stats = feature_stats();
        assert_eq!(stats.done, stats.total);
        assert_eq!(stats.stub, 0);
        assert_eq!(stats.planned, 0);
        assert_eq!(stats.partial, 0);
        // Audited average is intentionally deflated vs marketing claims.
        assert!(avg_parity() >= 40.0 && avg_parity() < 75.0);
    }

    #[test]
    fn ids_unique() {
        let mut seen = std::collections::HashSet::new();
        for f in FEATURES {
            assert!(seen.insert(f.id), "duplicate {}", f.id);
        }
    }

    #[test]
    fn every_feature_has_endpoint_and_parity() {
        for f in FEATURES {
            assert!(!f.endpoints.is_empty(), "{}", f.id);
            assert!(f.parity_pct > 0 && f.parity_pct <= 100, "{}", f.id);
        }
    }
}
