//! Full Datadog-surface feature inventory for tracking parity.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FeatureParityRow {
    pub id: String,
    pub name: String,
    pub category: String,
    pub status: String,
    pub parity_pct: u8,
    pub thine_strength: String,
    pub datadog_advantage: String,
    pub recommendation: String,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum FeatureStatus {
    /// Substantial working implementation
    Done,
    /// Working MVP API + storage
    Partial,
    /// Endpoint exists, placeholder/minimal
    Stub,
    /// Documented only — not exposed yet
    Planned,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum FeatureCategory {
    BuiltIn,
    Extensibility,
    ObservabilityInfra,
    Applications,
    Data,
    Logs,
}

#[derive(Debug, Clone, Serialize)]
pub struct FeatureEntry {
    pub id: &'static str,
    pub name: &'static str,
    pub category: FeatureCategory,
    pub status: FeatureStatus,
    pub endpoints: &'static [&'static str],
    pub notes: &'static str,
    /// Estimated functional parity vs Datadog SaaS for this surface (0–100)
    pub parity_pct: u8,
    pub thine_strength: &'static str,
    pub datadog_advantage: &'static str,
    pub recommendation: &'static str,
}

pub fn all_features() -> Vec<FeatureEntry> {
    FEATURES.to_vec()
}

pub fn feature_stats() -> FeatureStats {
    let mut stats = FeatureStats::default();
    for f in FEATURES {
        stats.total += 1;
        match f.status {
            FeatureStatus::Done => stats.done += 1,
            FeatureStatus::Partial => stats.partial += 1,
            FeatureStatus::Stub => stats.stub += 1,
            FeatureStatus::Planned => stats.planned += 1,
        }
    }
    stats
}

/// Honest audited parity vs Datadog SaaS — deflates marketing-inflated catalog scores.
pub fn audited_parity_pct(f: &FeatureEntry) -> u8 {
    // Explicit audits for surfaces called out as remaining debt.
    let explicit = match f.id {
        "apm" => Some(62),
        "notebooks" => Some(58),
        "error_tracking" => Some(58),
        "container_monitoring" => Some(60),
        "log_management" | "logs" => Some(58),
        "live_processes" => Some(65),
        "watchdog" | "anomaly_detection" | "forecast_monitors" => Some(48),
        "software_catalog" | "service_catalog" | "catalog" => Some(55),
        "observability_pipelines" | "pipelines" => Some(45),
        "continuous_profiler" | "profiler" => Some(40),
        "bits_ai" => Some(55),
        _ => None,
    };
    if let Some(v) = explicit {
        return v;
    }
    // Global haircut: claimed 90+ → −22, 80+ → −15, 70+ → −10.
    match f.parity_pct {
        90..=100 => f.parity_pct.saturating_sub(22),
        80..=89 => f.parity_pct.saturating_sub(15),
        70..=79 => f.parity_pct.saturating_sub(10),
        _ => f.parity_pct,
    }
}

pub fn parity_matrix() -> Vec<FeatureParityRow> {
    FEATURES
        .iter()
        .map(|f| FeatureParityRow {
            id: f.id.into(),
            name: f.name.into(),
            category: format!("{:?}", f.category),
            status: format!("{:?}", f.status).to_ascii_lowercase(),
            parity_pct: audited_parity_pct(f),
            thine_strength: f.thine_strength.into(),
            datadog_advantage: f.datadog_advantage.into(),
            recommendation: f.recommendation.into(),
        })
        .collect()
}

pub fn avg_parity() -> f64 {
    let rows = FEATURES;
    if rows.is_empty() {
        return 0.0;
    }
    rows.iter().map(|f| audited_parity_pct(f) as f64).sum::<f64>() / rows.len() as f64
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct FeatureStats {
    pub total: usize,
    pub done: usize,
    pub partial: usize,
    pub stub: usize,
    pub planned: usize,
    #[serde(default)]
    pub avg_parity_pct: f64,
}

pub fn feature_stats_with_parity() -> FeatureStats {
    let mut s = feature_stats();
    s.avg_parity_pct = (avg_parity() * 10.0).round() / 10.0;
    s
}

